"""Adds release signing (from android/key.properties) and R8 shrinking to the
build.gradle.kts generated by `flutter create`. Idempotent."""
import pathlib
import sys

path = pathlib.Path(__file__).resolve().parent.parent / "android" / "app" / "build.gradle.kts"
src = path.read_text()
if "key.properties" in src:
    print("android/app/build.gradle.kts already patched")
    sys.exit(0)

header = '''import java.io.FileInputStream
import java.util.Properties

'''

loader = '''
// Release signing: create android/key.properties (see key.properties.example).
// Without it, release builds fall back to debug signing; never upload those to Play.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
val hasReleaseKey = keystorePropertiesFile.exists()
if (hasReleaseKey) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}
'''

signing = '''    signingConfigs {
        create("release") {
            if (hasReleaseKey) {
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
            }
        }
    }

    buildTypes {'''

release = '''signingConfig = if (hasReleaseKey) {
                signingConfigs.getByName("release")
            } else {
                signingConfigs.getByName("debug")
            }
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )'''

old_release = 'signingConfig = signingConfigs.getByName("debug")'
if old_release not in src or "    buildTypes {" not in src or "\nandroid {" not in src:
    sys.exit("Unexpected build.gradle.kts template; apply the signing config by hand (see README).")

src = header + src
src = src.replace("\nandroid {", loader + "\nandroid {", 1)
src = src.replace("    buildTypes {", signing, 1)
src = src.replace(old_release, release, 1)
path.write_text(src)
print("Patched android/app/build.gradle.kts")
